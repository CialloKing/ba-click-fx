function decodeBase64Bytes(encoded)
{
  const binary = globalThis.atob(encoded);
  const bytes = new Uint8Array(binary.length);

  for (let index = 0; index < binary.length; index++)
  {
    bytes[index] = binary.charCodeAt(index);
  }

  return bytes;
}

function decodeRing3Alpha()
{
  const payload = decodeBase64Bytes(PACKED_RING3_ALPHA);

  if (payload.length !== RING3_PAYLOAD_LENGTH)
  {
    throw new Error('[BAClickFX] invalid Ring3 alpha payload');
  }

  const alpha = new Uint8Array(
    RING3_ALPHA_WIDTH * RING3_ALPHA_HEIGHT,
  );

  for (let v = 0; v < RING3_ALPHA_HEIGHT; v++)
  {
    const columnAlpha = payload[RING3_ALPHA_WIDTH + v];

    for (let x = 0; x < RING3_ALPHA_WIDTH; x++)
    {
      const index = v * RING3_ALPHA_WIDTH + x;
      const prediction = Math.round(
        payload[x] * columnAlpha / 255,
      );
      const packedResidual = payload[
        RING3_PREDICTOR_BYTES + (index >> 1)
      ];
      const residualCode = (index & 1) === 0
        ? packedResidual >> 4
        : packedResidual & 0x0f;

      alpha[index] =
        prediction + residualCode - RING3_RESIDUAL_OFFSET;
    }
  }

  return alpha;
}

function clampIndex(value, maximum)
{
  return Math.max(0, Math.min(maximum, value));
}

const RING3_ALPHA = decodeRing3Alpha();

function sampleRing3Alpha(u, v)
{
  const sampleX =
    Math.max(0, Math.min(1, u)) * RING3_ALPHA_WIDTH - 0.5;
  const sampleY =
    Math.max(0, Math.min(1, v)) * RING3_ALPHA_HEIGHT - 0.5;
  const sourceX = Math.floor(sampleX);
  const sourceY = Math.floor(sampleY);
  const x0 = clampIndex(sourceX, RING3_ALPHA_WIDTH - 1);
  const x1 = clampIndex(sourceX + 1, RING3_ALPHA_WIDTH - 1);
  const y0 = clampIndex(sourceY, RING3_ALPHA_HEIGHT - 1);
  const y1 = clampIndex(sourceY + 1, RING3_ALPHA_HEIGHT - 1);
  const blendX = sampleX - sourceX;
  const blendY = sampleY - sourceY;
  const lowerLeft = RING3_ALPHA[y0 * RING3_ALPHA_WIDTH + x0];
  const lowerRight = RING3_ALPHA[y0 * RING3_ALPHA_WIDTH + x1];
  const upperLeft = RING3_ALPHA[y1 * RING3_ALPHA_WIDTH + x0];
  const upperRight = RING3_ALPHA[y1 * RING3_ALPHA_WIDTH + x1];
  const lower = lowerLeft + (lowerRight - lowerLeft) * blendX;
  const upper = upperLeft + (upperRight - upperLeft) * blendX;

  return (lower + (upper - lower) * blendY) / 255;
}

